import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {chromium} from '../web/node_modules/playwright/index.mjs';
import {browserPath} from './browser-path.mjs';
const dir=await mkdtemp(join(tmpdir(),'sr-hints-')), url='http://127.0.0.1:18785';
const service=spawn('build/native/native/sightreading.exe',['--port','18785','--data-dir',dir],{stdio:'pipe'});
let browser,sequence=0,output='';
service.stderr.on('data',chunk=>output+=chunk);
const state=async()=>await(await fetch(url+'/api/v1/status')).json();
const until=async(fn)=>{for(let i=0;i<180;i++){if(await fn())return;if(service.exitCode!==null)throw Error(output);await new Promise(r=>setTimeout(r,100));}throw Error('Hint condition timeout '+output);};
const command=async(type,params={})=>{const r=await(await fetch(url+'/api/v1/command',{method:'POST',headers:{Origin:url,'Content-Type':'application/json'},body:JSON.stringify({version:1,id:++sequence,type,params})})).json();assert.equal(r.ok,true,JSON.stringify(r));return r.result;};
try {
 await until(async()=>{try{return(await state()).pianoReady;}catch{return false;}});
 await command('practice.configure',{staff:'grand',generator:'triads',mode:'wait',range:{min:48,max:84}});
 await command('practice.start');
 const before=(await state()).practice;
 await command('practice.configure',{hints:true});
 let staff=(await state()).practice;
 assert.equal(staff.running,before.running);
 assert.equal(staff.index,before.index);
 assert.deepEqual(staff.targets,before.targets);
 browser=await chromium.launch({executablePath:browserPath(),headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1100}}), errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(url+'/#staff');
 const hint=async enabled=>{
  const toggle=page.getByLabel('Hint mode',{exact:true});
  if(await toggle.isChecked()!==enabled)await toggle.click();
  await until(async()=>await toggle.isChecked()===enabled);
 };
 const shown=async expected=>{
  await until(async()=>{
   const actual=await page.locator('.piano-key[data-hint]').evaluateAll(keys=>keys.map(k=>({midiNote:Number(k.getAttribute('data-midi')),hand:k.getAttribute('data-hint')})));
   return actual.length===expected.length&&expected.every(n=>actual.some(k=>k.midiNote===n.midiNote&&k.hand===n.hand));
  });
  for(const n of expected) assert.equal(await page.locator(`.piano-key[data-midi="${n.midiNote}"]`).getAttribute('data-hint'),n.hand);
 };
 await shown(staff.hintKeys);
 assert.ok(staff.hintKeys.length>=3);
 await command('metronome.start');
 await command('virtual.noteOn',{source:'hint-held',channel:0,note:100,velocity:90,instance:999});
 await until(async()=>(await state()).heldNotes.some(n=>n.instance===999&&n.held));
 const stable=()=>state().then(s=>{assert.equal(s.metronome.running,true);assert.ok(s.heldNotes.some(n=>n.instance===999&&n.held));});
 await hint(false);
 await shown([]);await stable();
 assert.equal((await state()).practice.index,before.index);
 await hint(true);
 await shown((await state()).practice.hintKeys);
 await command('virtual.noteOff',{source:'hint-held',channel:0,instance:999});
 await command('practice.reset');
 staff=(await state()).practice;
 // Correct chord advances native targets and keyboard hints together.
 let attack=1000;
 for(const pitch of staff.targets[staff.index].pitches) await command('virtual.noteOn',{source:'hint-answer',channel:0,note:pitch.midiNote,velocity:90,instance:++attack});
 await until(async()=>(await state()).practice.index>staff.index);
 await command('virtual.disconnect',{source:'hint-answer'});
 await shown((await state()).practice.hintKeys);
 await command('practice.pause');
 await hint(false);
 assert.equal((await state()).practice.paused,true);
 await command('ear.configure',{mode:'interval',intervals:['M3'],directions:['down'],root:62,randomRoot:false});
 await page.getByRole('link',{name:/Ear Training/}).click();
 await shown([]);
 await hint(true);
 let ear=(await state()).ear;
 assert.deepEqual(ear.hintKeys.map(n=>n.midiNote).sort((a,b)=>a-b),[58,62]);
 await shown(ear.hintKeys);
 await command('ear.answer',{interval:'M3'});
 await shown([]);
 await command('ear.configure',{mode:'melody',groups:3,pitches:2,range:{min:48,max:72},continuous:false});
 ear=(await state()).ear;await shown(ear.hintKeys);
 assert.equal(ear.hintKeys.length,2);
 assert.deepEqual(ear.hintKeys.map(n=>n.midiNote).sort((a,b)=>a-b),[...ear.target.groups[0]].sort((a,b)=>a-b));
 const scoreBefore=ear.hits;
 await command('ear.answer',{pitches:ear.target.groups[0]});
 ear=(await state()).ear;await shown(ear.hintKeys);
 assert.equal(ear.hits,scoreBefore+1);
 assert.deepEqual(ear.hintKeys.map(n=>n.midiNote).sort((a,b)=>a-b),[...ear.target.groups[1]].sort((a,b)=>a-b));
 await command('ear.replay');
 await hint(false);
 assert.equal((await state()).ear.playing,true,'hint switch must not stop examples');
 await shown([]);
 await hint(true);
 await command('ear.stop');
 await command('ear.next');
 ear=(await state()).ear;
 for(const group of ear.target.groups)await command('ear.answer',{pitches:group});
 await shown([]);
 await page.getByRole('link',{name:/Play Along/}).click();await shown([]);
 await page.getByRole('link',{name:/Staff/}).click();await shown([]);
 await hint(true);
 await page.reload();
 await until(async()=>await page.getByLabel('Hint mode',{exact:true}).isChecked());
 await shown((await state()).practice.hintKeys);
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.getByLabel('Hint mode',{exact:true}).isVisible());
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 assert.deepEqual(errors,[]);
 assert.equal((await state()).metronome.running,true);
 console.log('PASS Staff/Ear hint toggles, chord/interval/melody targets, advancing/answered hints, pause/examples preserved, tab isolation, reload, mobile, live note and metronome continuity');
}finally{await browser?.close();if(service.exitCode===null){const done=new Promise(r=>service.once('exit',r));service.kill();await done;}await rm(dir,{recursive:true,force:true});}
